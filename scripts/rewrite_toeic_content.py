def academic_topic_sentence(item: dict[str, object]) -> str:
    """Build a workplace sentence for an academic-topic entry."""
    word = str(item.get("word", "")).strip()
    key = word.lower()
    pos = definition_pos(item)

    if key in ACADEMIC_EXAMPLE_OVERRIDES:
        return ACADEMIC_EXAMPLE_OVERRIDES[key]
    if pos == "verb":
        if key in INTRANSITIVE_VERBS:
            subject = INTRANSITIVE_SUBJECTS.get(key, "The process")
            return f"{subject} may {word} after the system is updated."
        object_phrase = ACADEMIC_VERB_OBJECTS.get(key, VERB_OBJECTS.get(key, "the process"))
        if object_phrase.endswith("before the audit"):
            return f"The operations team will {word} {object_phrase}."
        return f"The operations team will {word} {object_phrase} before the next audit."
    if pos == "adjective":
        if key in ACADEMIC_FORECAST_ADJECTIVES:
            return f"The {word} forecast affected the delivery schedule."
        if key in ACADEMIC_APPROACH_ADJECTIVES:
            return f"The company adopted {article_for(word)} {word} approach to product development."
        return f"The project required {article_for(word)} {word} process."
    if is_person(item) and key not in {"barometer", "meteor", "polymer", "crater", "glacier", "boulder"}:
        return f"The manager contacted the {word} about the project."
    if key in ACADEMIC_MATERIAL_NOUNS:
        return f"The manufacturer tested the {word} before production began."
    if key in ACADEMIC_AEROSPACE_NOUNS:
        return f"The aerospace company tracked the {word} during the mission."
    if key in ACADEMIC_GEOLOGY_NOUNS:
        return f"The construction team monitored the {word} before work began."
    if key in ACADEMIC_LAB_NOUNS:
        return f"The laboratory tested the {word} during product development."
    if key in ACADEMIC_PUBLISHING_NOUNS:
        return f"The editor checked the {word} before publication."
    if key in ACADEMIC_TRAINING_NOUNS:
        return f"The training department updated the {word} for new employees."
    if key in ACADEMIC_FACILITY_NOUNS:
        return f"The facilities team inspected the {word} before the event."
    if key in ACADEMIC_HR_NOUNS:
        return f"The HR team discussed {word} during a workplace training session."
    article = "" if key in ACADEMIC_UNCOUNTABLES else "the "
    if article:
        return f"The company considered the potential impact of {article}{word} on the project."
    return f"The company considered how {word} could affect the project."


def needs_academic_topic_rewrite(item: dict[str, object], sentence: str) -> bool:
    """Identify an academic/generated context that should become workplace-focused."""
    if str(item.get("topic", "")) not in ACADEMIC_TOPICS:
        return False
    lower = sentence.lower().strip()
    return academic_or_artificial(sentence) or lower.startswith((
        "the research team examined ",
        "the company adopted ",
        "the team will decide whether to ",
        "the company discussed ",
        "the company reviewed ",
        "the manager described ",
        "the project required ",
        "the operations team will ",
    )) or bool(re.match(r"^the .+ attended the meeting and signed", lower))


