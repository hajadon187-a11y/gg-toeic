def has_word(text: str, word: str) -> bool:
    # A phrase such as "cash flow" needs a word-boundary match on the entire
    # phrase, while a short function word still must not match inside a word.
    return bool(re.search(rf"(?<![A-Za-z]){re.escape(word)}(?![A-Za-z])", text, re.I))


def split_phrases(text: str) -> list[str]:
    return [re.sub(r"\s+", " ", p.strip()) for p in re.split(r"[,;|]", text) if p.strip()]


def definition_pos(item: dict[str, object]) -> str:
    word = str(item.get("word", "")).lower()
    definition = str(item.get("meaningEn", "")).strip().lower()
    if word in FUNCTION_WORDS:
        return "function"
    if definition.startswith(("a person", "a thing", "an ", "a ", "the ", "something", "information", "money", "a place")):
        return "noun"
    if definition.startswith(("used to ", "more than ", "not anything", "in the middle", "at a ", "in a ")):
        return "function"
    if word.endswith("ly") and definition.startswith(("in a ", "in the ", "to a ", "by ")):
        return "adverb"
    if definition.startswith("to ") or definition.startswith("to be "):
        return "verb"
    if definition.startswith(("relating to", "characterized by", "able to", "having ", "of or relating", "not able", "likely to", "causing ")):
        return "adjective"
    if word.endswith(("ness", "ment", "tion", "sion", "ity", "ship", "ance", "ence", "ism", "hood", "er", "or", "ist")):
        return "noun"
    if word.endswith(("ous", "ful", "less", "able", "ible", "ive", "al", "ic", "ical", "ary", "ed", "ing")):
        # Common -ing/-ed nouns are caught by their definitions below.
        if definition.startswith(("the act", "the process", "a person", "a thing", "an ", "a ", "the state")):
            return "noun"
        return "adjective"
    if definition.startswith(("a person", "a thing", "an ", "a ", "the act", "the process", "the state", "information", "money", "a place")):
        return "noun"
    return "noun"


def is_person(item: dict[str, object]) -> bool:
    text = str(item.get("meaningEn", "")).lower()
    word = str(item.get("word", "")).lower()
    if word in PERSON_HINTS:
        return True
    if word.endswith(("ist", "ian", "er", "or", "ee", "ant")) and len(word) > 5:
        return True
    return bool(re.search(r"\b(?:a person|someone who|people who|a [^.;,]+ employee)\b", text))


def academic_or_artificial(text: str) -> bool:
    lower = text.lower()
    return any(
        re.search(rf"(?<![A-Za-z]){re.escape(term)}(?![A-Za-z])", lower)
        for term in CAMPUS_TERMS + ARTIFICIAL_TERMS
    )


def contains_bad_term(text: str) -> bool:
    lower = text.lower()
    return any(
        re.search(rf"(?<![A-Za-z]){re.escape(term)}(?![A-Za-z])", lower)
        for term in CAMPUS_TERMS + ARTIFICIAL_TERMS
    )


def article_for(word: str) -> str:
    lower = word.lower()
    consonant_sound_vowels = ("use", "uni", "univ", "usual", "user", "one", "euro")
    if lower.startswith(consonant_sound_vowels):
        return "a"
    return "an" if lower[:1] in "aeiou" else "a"


def usable_example(item: dict[str, object], sentence: str) -> bool:
    word = str(item.get("word", ""))
    if not sentence or not has_word(sentence, word):
        return False
    if academic_or_artificial(sentence):
        return False
    lower = sentence.lower()
    if re.search(r"^the [a-z-]+ attended the meeting", lower) and not is_person(item):
        return False
    if re.search(r"\ba [aeiou][a-z]*\b", lower) or re.search(r"\ban [^aeiou\W][a-z]*\b", lower):
        return False
    if lower.startswith((
        "the team will ", "the process may ", "the company included the ",
        "the research team examined the ", "the company adopted a ",
        "the company adopted an ", "the report explains how the new system operates ",
        "the city council discussed the ", "the clinic recorded the ",
    )):
        return False
    topic = str(item.get("topic", ""))
    if topic in {"Academic", "Science", "Education"} and any(
        x in lower for x in ("the manager explained", "the manager argued", "manager used", "our manager")
    ):
        return False
    if len(sentence.split()) < 6 or len(sentence.split()) >  thirty_words():
        return False
    return True


def thirty_words() -> int:
    # Kept as a function so the quality threshold is easy to tune without
    # scattering a magic number through the validator.
    return 30


